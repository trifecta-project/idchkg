#!/usr/bin/env python3
"""One-time helper: download Natural Earth 110m countries GeoJSON, project to
equirectangular SVG paths matching the geomap viewBox (0 0 800 400), simplify
with Douglas-Peucker, and emit src/idchkg/_world_svg.py.

Requirements (not part of the package):
    pip install shapely requests

Run from the repo root:
    python scripts/generate_world_svg.py
"""

from __future__ import annotations

import json
from pathlib import Path

import requests
from shapely.geometry import shape
from shapely.ops import transform

URL = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/"
    "master/geojson/ne_110m_admin_0_countries.geojson"
)
CACHE = Path(__file__).parent / "ne_110m_countries.geojson"

W, H = 800, 400
# Douglas-Peucker tolerance in projected (pixel) coordinates.
TOLERANCE = 1.0


def fetch_geojson() -> dict:
    if CACHE.exists():
        print(f"Using cached {CACHE}")
        return json.loads(CACHE.read_text())
    print(f"Downloading {URL} ...")
    resp = requests.get(URL, timeout=60)
    resp.raise_for_status()
    CACHE.write_text(resp.text)
    print(f"Cached to {CACHE}")
    return resp.json()


def project_coord(lon: float, lat: float) -> tuple[float, float]:
    x = (lon + 180) / 360 * W
    y = (90 - lat) / 180 * H
    return (x, y)


def project_geom(geom):
    """Project a shapely geometry from lon/lat to SVG pixel coords."""
    return transform(lambda x, y, z=None: tuple(zip(*[project_coord(lo, la) for lo, la in zip(x, y)])), geom)


def geom_to_svg_path(geom) -> str:
    """Convert a (Multi)Polygon to an SVG path d attribute."""
    parts = []
    polys = geom.geoms if geom.geom_type == "MultiPolygon" else [geom]
    for poly in polys:
        for ring in [poly.exterior] + list(poly.interiors):
            coords = list(ring.coords)
            if len(coords) < 3:
                continue
            d = f"M{coords[0][0]:.1f} {coords[0][1]:.1f}"
            d += "".join(f"L{x:.1f} {y:.1f}" for x, y in coords[1:])
            d += "Z"
            parts.append(d)
    return "".join(parts)


def main():
    data = fetch_geojson()
    paths = []
    for feature in data["features"]:
        geom = shape(feature["geometry"])
        if geom.is_empty:
            continue
        projected = project_geom(geom)
        simplified = projected.simplify(TOLERANCE, preserve_topology=True)
        if simplified.is_empty:
            continue
        d = geom_to_svg_path(simplified)
        if d:
            paths.append(f'<path class="geo-land" d="{d}"/>')

    svg_block = "\n".join(paths)
    total_chars = len(svg_block)
    print(f"Generated {len(paths)} country paths, {total_chars} chars ({total_chars/1024:.0f} KB)")

    out = Path(__file__).resolve().parent.parent / "src" / "idchkg" / "_world_svg.py"
    module_text = (
        '"""Pre-projected Natural Earth 110m country outlines as SVG <path> elements.\n'
        "\n"
        "Projection: equirectangular, matching the geomap viewBox 0 0 800 400.\n"
        'Generated by scripts/generate_world_svg.py -- do not edit by hand.\n'
        '"""\n'
        "\n"
        'COUNTRIES_SVG = """\\\n'
        f"{svg_block}\n"
        '"""\n'
    )
    out.write_text(module_text, encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
